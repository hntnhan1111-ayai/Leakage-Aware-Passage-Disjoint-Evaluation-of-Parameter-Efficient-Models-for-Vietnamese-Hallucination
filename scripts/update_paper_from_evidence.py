import argparse
import json
from pathlib import Path
import re


def load_summary(evidence_dir):
    summary_path = evidence_dir / "summary_metrics.json"
    matrix_path = evidence_dir / "confusion_matrix.png"
    errors_path = evidence_dir / "selected_error_cases.md"
    audit_path = evidence_dir / "code_paper_consistency_audit.md"
    missing = [str(p) for p in [summary_path, matrix_path, errors_path, audit_path] if not p.exists() or p.stat().st_size == 0]
    if missing:
        raise FileNotFoundError("Paper update requires generated evidence files: " + ", ".join(missing))
    return json.loads(summary_path.read_text(encoding="utf-8")), audit_path.read_text(encoding="utf-8", errors="replace")


def per_class_f1(report, label):
    return float(report[label]["f1-score"])


def build_block(summary, audit, evidence_dir):
    report = summary["classification_report"]
    rank_note = "Audited implementation evidence indicates LoRA rank r=128 in the current scripts; r=64 claims must not be used unless reproduced by a separate run."
    if "r=64" in audit and "'r': 128" not in audit:
        rank_note = "The audited evidence did not find an r=128 implementation conflict."
    return rf"""
\subsection{{Generated Evidence Package}}
The paper evidence in \texttt{{{evidence_dir}}} was generated by the repository scripts. This section should be refreshed only from \texttt{{summary\_metrics.json}} and related generated artifacts.

\begin{{table}}[ht]
\centering
\caption{{Generated ViHallu test metrics}}
\begin{{tabular}}{{lrrrrrr}}
\hline
Run & Accuracy & Macro-F1 & Weighted-F1 & no F1 & intrinsic F1 & extrinsic F1 \\
\hline
Current evidence & {summary["accuracy"]:.4f} & {summary["macro_f1"]:.4f} & {summary["weighted_f1"]:.4f} & {per_class_f1(report, "no"):.4f} & {per_class_f1(report, "intrinsic"):.4f} & {per_class_f1(report, "extrinsic"):.4f} \\
\hline
\end{{tabular}}
\end{{table}}

\begin{{figure}}[ht]
\centering
\includegraphics[width=0.75\linewidth]{{../{evidence_dir}/confusion_matrix.png}}
\caption{{Confusion matrix generated from the evaluated ViHallu predictions.}}
\end{{figure}}

\paragraph{{Qualitative errors.}}
Representative error cases are stored in \texttt{{{evidence_dir}/selected\_error\_cases.md}} and should be summarized manually after inspection.

\paragraph{{Reproducibility.}}
The evidence run uses seed 42, full \texttt{{vihallu-test.csv}} by default, label order \texttt{{no}}, \texttt{{intrinsic}}, \texttt{{extrinsic}}, deterministic decoding for generated prediction paths, and artifact validation through \texttt{{validation\_report.md}}. {rank_note}
"""


def update_paper(paper, evidence_dir):
    summary, audit = load_summary(evidence_dir)
    text = paper.read_text(encoding="utf-8", errors="replace")
    text = text.replace("robust framework", "lightweight and reproducible empirical recipe")
    text = text.replace("state-of-the-art \\textbf{Macro-F1", "generated \\textbf{Macro-F1")
    text = re.sub(r"QLoRA \(\$r=64\$\)", "QLoRA (audited current scripts use $r=128$)", text)
    block = build_block(summary, audit, evidence_dir)
    marker_start = "% BEGIN GENERATED EVIDENCE PACKAGE"
    marker_end = "% END GENERATED EVIDENCE PACKAGE"
    generated = marker_start + "\n" + block + "\n" + marker_end
    if marker_start in text and marker_end in text:
        text = re.sub(re.escape(marker_start) + r".*?" + re.escape(marker_end), generated, text, flags=re.S)
    else:
        insert_at = text.rfind("\\section{Conclusion}")
        if insert_at == -1:
            insert_at = len(text)
        text = text[:insert_at] + generated + "\n\n" + text[insert_at:]
    paper.write_text(text, encoding="utf-8")
    print(f"Updated {paper}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--paper", default="materials/paper.tex")
    parser.add_argument("--evidence_dir", default="results/paper_evidence")
    args = parser.parse_args()
    update_paper(Path(args.paper), Path(args.evidence_dir))


if __name__ == "__main__":
    main()
